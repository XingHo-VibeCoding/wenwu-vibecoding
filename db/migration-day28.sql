-- 迁移脚本：新增「仪器面板图 + 按键说明」两张表（Day 28）
-- 依据：Day 28 板块 1 数据建模（文伍拍板方案 A：两张表，与
--       scenes/steps 的「父表 + 子表」范式同构）
-- 执行位置：CloudBase 控制台 → 数据管理 → SQL 编辑器
--
-- ⚠️ 两条铁律（Day 28 清单定的）：
--   1. 本脚本【绝不 DROP】：线上已有真数据，db/schema.sql 开头
--      含 DROP，绝不可整份重跑。本脚本用 IF NOT EXISTS，可重复执行。
--   2. 新表必须单独 GRANT：GRANT ... ON ALL TABLES 不会覆盖
--      本脚本新建的表。缺授权 → 新接口稳定 500，而老读接口
--      完全不受影响（不对称，极易误诊，项目 Day 22 踩过一次）。
-- ============================================================


-- ------------------------------------------------------------
-- 表 1：panels  仪器面板图（一行一张面板图）
-- 关联键：device_type（与 instruments.device_type 同一 CHECK 枚举）
-- 本期每台 1 张前面板图，order_no 恒为 1；将来加后面板图 = 追加行
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS panels (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_type text    NOT NULL CHECK (device_type IN (
                        'dc_power', 'multimeter', 'oscilloscope',
                        'signal_gen', 'lcr', 'curve_tracer')),
  device_name text    NOT NULL,
  image_path  text    NOT NULL,
  image_desc  text    NOT NULL,
  source      text    NOT NULL,
  order_no    integer NOT NULL DEFAULT 1 CHECK (order_no >= 1),
  CONSTRAINT panels_device_order_unique UNIQUE (device_type, order_no)
);


-- ------------------------------------------------------------
-- 表 2：panel_keys  仪器按键说明（一行一个按键/部件）
-- 按键属于「整台仪器」而非某张图（图示仪的编号表跨主面板/
-- 测试台/后面板连续），所以挂 device_type，不挂图片
-- 不加外键：device_type 是自然键，靠 CHECK 枚举保证一致（与
-- instruments 独立表的风格一致）
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS panel_keys (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_type   text    NOT NULL CHECK (device_type IN (
                          'dc_power', 'multimeter', 'oscilloscope',
                          'signal_gen', 'lcr', 'curve_tracer')),
  order_no      integer NOT NULL CHECK (order_no >= 1),
  key_name      text    NOT NULL,
  function_desc text,
  source        text    NOT NULL,
  CONSTRAINT panel_keys_device_order_unique UNIQUE (device_type, order_no)
);


-- ------------------------------------------------------------
-- 授权：只读（与 5 张老表同一角色 anon）
-- 缺这两行 → /api/panels 稳定 500，老接口不受影响
-- ------------------------------------------------------------
GRANT SELECT ON panels     TO anon;
GRANT SELECT ON panel_keys TO anon;


-- ------------------------------------------------------------
-- 字段注释（与 schema.sql 风格一致）
-- ------------------------------------------------------------
COMMENT ON TABLE panels IS '仪器面板图表：一行一张面板图（Day 28 新增），device_type 与 instruments 的枚举同口径';
COMMENT ON COLUMN panels.device_type IS '仪器类型枚举，与 instruments.device_type 同一 CHECK 枚举（关联键）';
COMMENT ON COLUMN panels.device_name IS '仪器类型 + 型号，写法与 instruments.device_name 完全一致';
COMMENT ON COLUMN panels.image_path  IS '面板图相对路径（相对前端部署根），对应静态托管桶 wenwu-vibecoding/ 下的文件';
COMMENT ON COLUMN panels.image_desc  IS '图内容简述，如「前面板」「主面板」';
COMMENT ON COLUMN panels.source      IS '出处：手册名 + 页脚印刷页码（沿用 seed.sql 的 source 口径），便于回查';
COMMENT ON COLUMN panels.order_no    IS '同一仪器的第几张图；本期每台 1 张恒为 1';

COMMENT ON TABLE panel_keys IS '仪器按键说明表：一行一个按键/部件（Day 28 新增），key_name 供前端搜索';
COMMENT ON COLUMN panel_keys.device_type   IS '仪器类型枚举，与 panels.device_type 同口径；不加外键，靠 CHECK 约束';
COMMENT ON COLUMN panel_keys.order_no      IS '说明书面板介绍中的原始编号（图上圈号），同仪器内不重号';
COMMENT ON COLUMN panel_keys.key_name      IS '按键/部件名；分组条目以「（分组）」结尾或含「区」字';
COMMENT ON COLUMN panel_keys.function_desc IS '功能说明，转录自说明书原文（轻排版调整）；说明书只给名称没给说明时存 NULL（如 LCR-6002），不编造';
COMMENT ON COLUMN panel_keys.source        IS '出处：手册名 + 页脚印刷页码';
