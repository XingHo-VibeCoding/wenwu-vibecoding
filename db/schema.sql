-- 字段命名与 api-contract.md 的差异（Day 16 已拍板，会回写契约）：
--   desc  -> description   desc 是 SQL 保留字（ORDER BY x DESC），直接用会语法报错
--   time  -> time_cost     time 是 PG 的类型名，容易看混
--   text  -> content       text 同为类型名，text text NOT NULL 读写别扭
