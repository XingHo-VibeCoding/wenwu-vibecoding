-- ------------------------------------------------------------
-- 第 0 步：清掉旧表 —— 这就是「可重复执行」的实现方式
-- 反着删：先删子表，再删父表；CASCADE 顺带带走依赖它的索引和外键
-- ------------------------------------------------------------
DROP TABLE IF EXISTS tasks       CASCADE;
DROP TABLE IF EXISTS steps       CASCADE;
DROP TABLE IF EXISTS resources   CASCADE;
DROP TABLE IF EXISTS instruments CASCADE;
DROP TABLE IF EXISTS scenes      CASCADE;


-- ------------------------------------------------------------
-- 第 1 张：scenes  场景（主表，4 行）
-- 一行 = 一个场景。它是 steps 和 tasks 的「父表」
-- ------------------------------------------------------------
CREATE TABLE scenes (
  id             text     PRIMARY KEY,
  no             text     NOT NULL UNIQUE,
  name           text     NOT NULL,
  method         text     NOT NULL,
  description    text     NOT NULL,
  device_note    text     NOT NULL DEFAULT 'Android + Windows',
  prerequisite   text     NOT NULL,
  step_count     integer  NOT NULL DEFAULT 0 CHECK (step_count >= 0),
  difficulty     text     NOT NULL DEFAULT '待实测',
  time_cost      text     NOT NULL DEFAULT '待实测',
  measure_status text     NOT NULL DEFAULT 'pending'
                          CHECK (measure_status IN ('measured', 'pending'))
);


-- ------------------------------------------------------------
-- 第 2 张：steps  步骤（子表，20 行 = 4 个场景 x 5 步）
-- scene_id 指向 scenes.id —— 今天要掌握的那条关联字段
-- ------------------------------------------------------------
CREATE TABLE steps (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scene_id         text    NOT NULL REFERENCES scenes (id) ON DELETE CASCADE,
  order_no         integer NOT NULL CHECK (order_no >= 1),
  content          text    NOT NULL,
  difficulty_level integer CHECK (difficulty_level BETWEEN 1 AND 5),
  time_minutes     integer CHECK (time_minutes >= 0),
  caution          text,
  measure_status   text    NOT NULL DEFAULT 'pending'
                           CHECK (measure_status IN ('measured', 'pending')),
  CONSTRAINT steps_scene_order_unique UNIQUE (scene_id, order_no)
);

-- PG 不会给外键自动建索引，手动补一个
CREATE INDEX idx_steps_scene_id ON steps (scene_id);


-- ------------------------------------------------------------
-- 第 3 张：resources  资源入口（独立表，6 行）
-- 谁都不挂靠，每条链接自己就是完整数据
-- ------------------------------------------------------------
CREATE TABLE resources (
  id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name    text    NOT NULL,
  url     text    NOT NULL CHECK (url ~ '^https://'),
  purpose text    NOT NULL,
  kind    text    NOT NULL CHECK (kind IN ('official', 'community'))
);


-- ------------------------------------------------------------
-- 第 4 张：instruments  仪器操作条目（独立表，34 行 / 6 台仪器）
-- keywords 和 step_list 用 PG 原生数组类型 text[]
-- ------------------------------------------------------------
CREATE TABLE instruments (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_name text    NOT NULL,
  title       text    NOT NULL,
  keywords    text[]  NOT NULL,
  step_list   text[]  NOT NULL,
  source      text    NOT NULL,
  device_type text    NOT NULL CHECK (device_type IN (
                        'dc_power', 'multimeter', 'oscilloscope',
                        'signal_gen', 'lcr', 'curve_tracer'))
);


-- ------------------------------------------------------------
-- 第 5 张：tasks  任务索引（独立表，8 行）
-- scene_id 也指向 scenes.id：8 个跳转按钮 -> 4 个场景
-- ------------------------------------------------------------
CREATE TABLE tasks (
  id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label    text    NOT NULL,
  scene_id text    NOT NULL REFERENCES scenes (id) ON DELETE CASCADE,
  keywords text[]
);

CREATE INDEX idx_tasks_scene_id ON tasks (scene_id);


